<?php
/**
 * Загрузчик модулей темы.
 *
 * Каждый модуль отвечает за одну задачу и подключается здесь в порядке
 * зависимостей: сначала базовые вещи (константы, иконки, хелперы), затем
 * регистрация данных, и только потом то, что этими данными пользуется.
 *
 * @package MusicArtPlus
 */

defined( 'ABSPATH' ) || exit;

// Локальные настройки сервера, если их неудобно держать в wp-config.php.
// Файл не попадает в репозиторий — см. .gitignore.
if ( is_readable( MAP_DIR . '/inc/config.local.php' ) ) {
	require_once MAP_DIR . '/inc/config.local.php';
}

/**
 * Список модулей в порядке подключения.
 *
 * @var string[]
 */
$map_modules = array(
	'config',         // Константы, реквизиты, значения по умолчанию.
	'icons',          // SVG-иконки (сгенерирован из tools/generator.py).
	'helpers',        // Общие хелперы шаблонов.
	'nav',            // Меню шапки и подвала.
	'template-tags',  // Разметка карточек и повторяющихся секций.
	'setup',          // Поддержка возможностей WordPress, меню, размеры картинок.
	'performance',    // Ускорение фронтенда: чистка лишнего, ресурсные подсказки.
	'assets',         // Подключение CSS и JS.
	'post-types',     // Типы записей: педагоги, направления, отзывы.
	'acf',            // Настройка ACF: синхронизация, страница опций.
	'acf-fields',     // Группы полей ACF, объявленные в коде.
	'moyklass',       // Клиент API CRM «Мой класс».
	'rest',           // REST-маршруты темы (расписание, заявки).
	'booking',        // Обработка формы записи.
	'admin',          // Экран настроек и диагностика интеграции.
	'seed',           // Первичное наполнение контентом.
);

foreach ( $map_modules as $map_module ) {
	$map_file = MAP_DIR . '/inc/' . $map_module . '.php';

	if ( is_readable( $map_file ) ) {
		require_once $map_file;
	}
}

unset( $map_modules, $map_module, $map_file );
